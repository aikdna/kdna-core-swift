#!/usr/bin/env node
// Regenerates the committed sections conformance fixture through the
// RELEASED creation path and verifies byte equality with the checked-in
// asset.
//
// Usage:
//   KDNA_CORE_RELEASE_ROOT=<path to an installed @aikdna/kdna-core> \
//     node regenerate-sections-fixture.mjs
//
// The pinned release is checked at run time: the script refuses any core
// package whose version is not 0.36.0. No absolute paths are recorded here;
// the release root is supplied by the caller.

import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PINNED_CORE = '0.36.0';
const directory = dirname(fileURLToPath(import.meta.url));
const root = process.env.KDNA_CORE_RELEASE_ROOT;
if (!root) {
  console.error('FAIL: set KDNA_CORE_RELEASE_ROOT to the installed @aikdna/kdna-core directory');
  process.exit(1);
}
const require = createRequire(join(root, 'package.json'));
const coreManifest = require(join(root, 'package.json'));
if (coreManifest.name !== '@aikdna/kdna-core' || coreManifest.version !== PINNED_CORE) {
  console.error(`FAIL: expected @aikdna/kdna-core@${PINNED_CORE}, found ${coreManifest.name}@${coreManifest.version}`);
  process.exit(1);
}
const creation = require(join(root, 'src/public-contract/creation-sections-node.js'));
const sectionsContract = require(join(root, 'src/public-contract/sections/contract.json'));

const authorship = JSON.parse(readFileSync(join(directory, 'sections-fixture-craft-course-0.1.0.authorship.json'), 'utf8'));
const committed = readFileSync(join(directory, 'sections-fixture-craft-course-0.1.0.kdna'));

const admitted = creation.admitNativeCreationRequest({
  request_id: 'regenerate-sections-fixture',
  tuple: sectionsContract.module.versionTuple,
  operation: 'create_public_asset',
  timeout_ms: 30000,
});
if (!admitted.request) throw new Error(`admission failed: ${JSON.stringify(admitted).slice(0, 300)}`);
const authority = creation.createNativeCreationAuthority(async () => true);
const result = await creation.createSectionAssetNode(
  { manifest: authorship.retainedManifest, payload: authorship.payload, members: [] },
  admitted.request,
  authority,
);
if (result.status !== 'produced') throw new Error(`creation failed: ${JSON.stringify(result).slice(0, 600)}`);
const bytes = Buffer.from(result.bytes);
const matches = bytes.length === committed.length && bytes.equals(committed);
console.log(matches ? 'OK: regenerated bytes are identical to the committed fixture' : 'FAIL: regenerated bytes differ from the committed fixture');
console.log('file sha256:', createHash('sha256').update(bytes).digest('hex'));
console.log('authorship fileSha256:', authorship.fileSha256, '| bytes:', authorship.fileBytes);
process.exit(matches ? 0 : 1);
